// Biology. Authored to the same three rules the math courses follow, which
// matter more here than they look:
//
//  * `fill` has NO alternate-answer support, and biology is the subject most
//    likely to trip on that — "mitochondria"/"mitochondrion" are both right in
//    English but only one is right to the grader. Every prompt below is written
//    so exactly ONE word fits: "an organelle called a ______" forces the
//    singular, "______ transport" forces the adjective, and so on. If a term
//    has two accepted spellings it does not appear as a fill.
//  * `slider` answers are whole numbers on the default 0.5 step, so the
//    neighbouring whole number always grades wrong. Counts are kept small
//    enough to aim (a 0.5 step needs a track no wider than 50).
//  * Genetics ratios are asked as "how many of the 4 offspring", not as
//    percentages — 25/50/75 on a 0-100 track would need a step so coarse that
//    a near miss would grade correct.
